# ---------------------------------------------------------------------------
# PNG encoder
# ---------------------------------------------------------------------------

_PNG_SIG = b"\x89PNG\r\n\x1a\n"


def _read_ihdr(png: bytes) -> tuple[int, int, int, int]:
    assert png[:8] == _PNG_SIG
    # First chunk must be IHDR: len(4) | "IHDR" | payload(13) | crc(4).
    length = struct.unpack(">I", png[8:12])[0]
    assert length == 13
    assert png[12:16] == b"IHDR"
    payload = png[16 : 16 + 13]
    width, height, bit_depth, color_type = struct.unpack(">IIBB", payload[:10])
    return width, height, bit_depth, color_type


def test_png_encoder_header_and_dimensions():
    rgb = bytes([10, 20, 30]) * (4 * 3)  # 4x3 image
    png = encode_rgb_png(4, 3, rgb)
    w, h, depth, ctype = _read_ihdr(png)
    assert (w, h, depth, ctype) == (4, 3, 8, 2)
    # IEND must be the last 12 bytes of the file.
    assert png[-12:-8] == b"\x00\x00\x00\x00"  # IEND payload length = 0
    assert png[-8:-4] == b"IEND"


def test_png_encoder_rgb_buffer_size_validation():
    with pytest.raises(ValueError):
        encode_rgb_png(2, 2, b"\x00" * 11)  # should be 12 bytes


def test_png_encoder_rejects_non_positive_dims():
    with pytest.raises(ValueError):
        encode_rgb_png(0, 1, b"")
    with pytest.raises(ValueError):
        encode_rgb_png(1, -1, b"")


def test_png_encoder_roundtrip_via_zlib_decompress():
    """IDAT payload must decompress to filter-byte-prefixed scanlines."""
    width, height = 3, 2
    rgb = bytes(range(width * height * 3))
    png = encode_rgb_png(width, height, rgb)

    # Walk chunks to find IDAT.
    pos = 8
    idat = None
    while pos < len(png):
        length = struct.unpack(">I", png[pos : pos + 4])[0]
        tag = png[pos + 4 : pos + 8]
        payload = png[pos + 8 : pos + 8 + length]
        if tag == b"IDAT":
            idat = payload
            break
        pos += 12 + length
    assert idat is not None
    raw = zlib.decompress(idat)
    stride = width * 3
    assert len(raw) == height * (1 + stride)
    for row in range(height):
        start = row * (1 + stride)
        assert raw[start] == 0  # filter type: None
        assert raw[start + 1 : start + 1 + stride] == rgb[row * stride : (row + 1) * stride]


# ---------------------------------------------------------------------------
# Generators — determinism and shape
# ---------------------------------------------------------------------------

@pytest.mark.parametrize(
    "fn,kwargs",
    [
        (gen_clean_solid, {"gray_level": 128}),
        (gen_edge_half, {}),
        (gen_grid_64, {"cell": 64}),
        (gen_gradient_h, {}),
        (gen_corners_fiducials, {"marker_size": 32, "inset": 10}),
    ],
)
def test_each_generator_is_deterministic(fn, kwargs):
    a = fn(width=320, height=200, **kwargs)
    b = fn(width=320, height=200, **kwargs)
    assert a == b


@pytest.mark.parametrize("entry", list(B1_ARTIFACTS))
def test_registry_renders_deterministically_and_matches_target_resolution(entry):
    a = render_artifact(entry, width=DEFAULT_WIDTH, height=DEFAULT_HEIGHT)
    b = render_artifact(entry, width=DEFAULT_WIDTH, height=DEFAULT_HEIGHT)
    assert a == b
    w, h, depth, ctype = _read_ihdr(a)
    assert (w, h, depth, ctype) == (DEFAULT_WIDTH, DEFAULT_HEIGHT, 8, 2)


def test_clean_solid_rejects_out_of_range_gray():
    with pytest.raises(ValueError):
        gen_clean_solid(16, 16, gray_level=300)


def test_gradient_h_requires_width_ge_2():
    with pytest.raises(ValueError):
        gen_gradient_h(width=1, height=4)


def test_corners_fiducials_rejects_overlap():
    # marker_size + 2*inset must be < min(width, height)
    with pytest.raises(ValueError):
        gen_corners_fiducials(width=50, height=50, marker_size=30, inset=20)


# ---------------------------------------------------------------------------
# Manifest coherence
# ---------------------------------------------------------------------------

def test_registry_has_the_expected_locked_five_mandatory_artifacts():
    ids = [e["artifact_id"] for e in B1_ARTIFACTS]
    assert ids == [
        "b1-clean-solid",
        "b1-edge-half",
        "b1-grid-64",
        "b1-gradient-h",
        "b1-corners-fiducials",
    ]
    assert all(e["mandatory"] for e in B1_ARTIFACTS)


def test_build_manifest_matches_registry_and_sha256_is_self_consistent():
    manifest = build_manifest(width=DEFAULT_WIDTH, height=DEFAULT_HEIGHT)
    assert manifest["set_id"] == SET_ID
    assert manifest["set_version"] == SET_VERSION
    assert manifest["resolution"] == [DEFAULT_WIDTH, DEFAULT_HEIGHT]
    assert len(manifest["artifacts"]) == len(B1_ARTIFACTS)
    for m_entry, src in zip(manifest["artifacts"], B1_ARTIFACTS):
        png = render_artifact(src, width=DEFAULT_WIDTH, height=DEFAULT_HEIGHT)
        assert m_entry["artifact_id"] == src["artifact_id"]
        assert m_entry["sha256"] == hashlib.sha256(png).hexdigest()
        assert m_entry["byte_size"] == len(png)
        assert m_entry["generator_function"] == src["generator"]
        assert m_entry["measurement_target"] == src["measurement_target"]


def test_on_disk_manifest_matches_regeneration_and_assets_match_manifest():
    """Against the live repo root: the locked manifest verifies clean."""
    manifest_path = _REPO_ROOT / "V2_BENCHMARK_SET" / "V2_BENCHMARK_SET_MANIFEST.json"
    if not manifest_path.exists():  # pragma: no cover — safety in partial checkouts
        pytest.skip("V2 benchmark set not rendered yet")
    errors = verify_on_disk(_REPO_ROOT)
    assert errors == [], f"on-disk verification failed: {errors}"


def test_on_disk_manifest_declares_b1_set_and_has_five_artifacts():
    manifest_path = _REPO_ROOT / "V2_BENCHMARK_SET" / "V2_BENCHMARK_SET_MANIFEST.json"
    if not manifest_path.exists():  # pragma: no cover
        pytest.skip("V2 benchmark set not rendered yet")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["set_id"] == "V2-BENCH-B1"
    assert manifest["set_version"] == "1.0.0"
    assert len(manifest["artifacts"]) == 5
    assert all(a["mandatory"] for a in manifest["artifacts"])
