"""Render and verify the V2 B1 benchmark set.

Two modes:

    render  -- (re)render all mandatory B1 artifacts to disk and write
               V2_BENCHMARK_SET_MANIFEST.json with fresh SHA-256 values.
    verify  -- re-render in-memory, compare SHA-256 of each artifact to the
               value currently recorded in the manifest, and check the
               on-disk bytes match the regenerated bytes. Returns a non-zero
               exit code on any mismatch.

Neither mode touches the V1 substrate. This is V2-only, additive code.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from . import DEFAULT_HEIGHT, DEFAULT_WIDTH, SET_ID, SET_VERSION
from .generators import B1_ARTIFACTS, render_artifact


def _sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _asset_path(root: Path, artifact_id: str) -> Path:
    return root / "V2_BENCHMARK_SET" / "assets" / f"{artifact_id}.png"


def _manifest_path(root: Path) -> Path:
    return root / "V2_BENCHMARK_SET" / "V2_BENCHMARK_SET_MANIFEST.json"


def _relative_asset_path(artifact_id: str) -> str:
    # POSIX-style path for portability across Windows / Linux.
    return f"V2_BENCHMARK_SET/assets/{artifact_id}.png"


def build_manifest(
    width: int = DEFAULT_WIDTH,
    height: int = DEFAULT_HEIGHT,
    locked_on: str = "2026-04-14",
) -> dict:
    """Build the in-memory manifest by rendering every B1 artifact.

    Does not touch disk. Useful for verify mode and for tests.
    """
    artifacts_out = []
    for entry in B1_ARTIFACTS:
        png_bytes = render_artifact(entry, width=width, height=height)
        artifacts_out.append(
            {
                "artifact_id": entry["artifact_id"],
                "family": entry["family"],
                "generator_module": "aurexis_lang.v2_benchmark.generators",
                "generator_function": entry["generator"],
                "generator_params": dict(entry["params"]),
                "rendered_path": _relative_asset_path(entry["artifact_id"]),
                "sha256": _sha256_hex(png_bytes),
                "byte_size": len(png_bytes),
                "measurement_target": entry["measurement_target"],
                "mandatory": entry["mandatory"],
                "notes": entry["notes"],
            }
        )
    return {
        "set_id": SET_ID,
        "set_version": SET_VERSION,
        "locked_on": locked_on,
        "resolution": [width, height],
        "resolution_note": (
            "Locked target render resolution. Assumed native for MSI G27C4X "
            "per prior context (1920x1080). If pilot-start verification shows "
            "a different native resolution, the set must be re-rendered and "
            "the set_version must be bumped."
        ),
        "encoder": {
            "name": "aurexis_lang.v2_benchmark.png_writer.encode_rgb_png",
            "strategy": "uncompressed zlib (DEFLATE stored blocks)",
            "reason": (
                "Byte-deterministic across Python versions, platforms, and "
                "zlib implementations, so SHA-256 values stay stable."
            ),
        },
        "artifacts": artifacts_out,
    }


def render_to_disk(root: Path, manifest: dict) -> None:
    for entry in manifest["artifacts"]:
        src = next(a for a in B1_ARTIFACTS if a["artifact_id"] == entry["artifact_id"])
        png_bytes = render_artifact(
            src, width=manifest["resolution"][0], height=manifest["resolution"][1]
        )
        asset = _asset_path(root, entry["artifact_id"])
        asset.parent.mkdir(parents=True, exist_ok=True)
        asset.write_bytes(png_bytes)
    _manifest_path(root).write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )


def verify_on_disk(root: Path) -> list[str]:
    """Return a list of error strings. Empty list == verified clean."""
    errors: list[str] = []
    manifest_path = _manifest_path(root)
    if not manifest_path.exists():
        return [f"manifest missing: {manifest_path}"]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    width, height = manifest["resolution"]

    for entry in manifest["artifacts"]:
        src = next(
            (a for a in B1_ARTIFACTS if a["artifact_id"] == entry["artifact_id"]),
            None,
        )
        if src is None:
            errors.append(
                f"{entry['artifact_id']}: not in B1_ARTIFACTS registry"
            )
            continue
        regenerated = render_artifact(src, width=width, height=height)
        recomputed_sha = _sha256_hex(regenerated)
        if recomputed_sha != entry["sha256"]:
            errors.append(
                f"{entry['artifact_id']}: regenerated sha256 {recomputed_sha} "
                f"does not match manifest {entry['sha256']}"
            )
        asset = _asset_path(root, entry["artifact_id"])
        if not asset.exists():
            errors.append(f"{entry['artifact_id']}: asset missing at {asset}")
            continue
        disk_bytes = asset.read_bytes()
        if disk_bytes != regenerated:
            errors.append(
                f"{entry['artifact_id']}: on-disk bytes differ from regenerated"
            )
        if len(disk_bytes) != entry.get("byte_size", len(disk_bytes)):
            errors.append(
                f"{entry['artifact_id']}: manifest byte_size mismatch"
            )
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "mode", choices=("render", "verify"), help="render or verify the B1 set"
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path.cwd(),
        help="repo root (the folder that contains V2_BENCHMARK_SET/)",
    )
    parser.add_argument("--width", type=int, default=DEFAULT_WIDTH)
    parser.add_argument("--height", type=int, default=DEFAULT_HEIGHT)
    parser.add_argument("--locked-on", type=str, default="2026-04-14")
    args = parser.parse_args(argv)

    if args.mode == "render":
        manifest = build_manifest(
            width=args.width, height=args.height, locked_on=args.locked_on
        )
        render_to_disk(args.root, manifest)
        print(
            f"rendered {len(manifest['artifacts'])} B1 artifacts at "
            f"{args.width}x{args.height} under {args.root}/V2_BENCHMARK_SET/"
        )
        return 0

    errors = verify_on_disk(args.root)
    if errors:
        for e in errors:
            print(f"FAIL: {e}")
        return 1
    print("OK: V2 benchmark set verified (manifest, checksums, bytes)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
